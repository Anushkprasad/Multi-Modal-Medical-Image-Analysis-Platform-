"""
Pydantic schemas for the prediction API.

These models define the shape of API request/response data
and are also used by the Gemini service for structured output.
"""

from __future__ import annotations

from typing import Any, Optional
from pydantic import BaseModel


class RadiologyReport(BaseModel):
    """
    Structured radiology report generated by the Gemini service.

    All four fields are required so the report schema is consistent
    whether it comes from a real Gemini call or the mock fallback.
    """

    impression: str
    """A concise overall clinical impression based only on model outputs."""

    findings: str
    """Specific findings reported by the YOLO, DenseNet, and multimodal models."""

    recommendations: str
    """Suggested follow-up actions if the model outputs indicate abnormalities."""

    model_summary: str
    """Technical summary of what each of the three AI models detected."""


class PredictionResponse(BaseModel):
    """
    Full response returned by POST /api/v1/predict.
    Includes a unique request_id for audit retrieval.
    """

    request_id: str
    filename: str
    yolo_result: dict[str, Any]
    densenet_result: dict[str, Any]
    multimodal_result: dict[str, Any]
    gemini_report: RadiologyReport


class AuditRecord(BaseModel):
    """
    Response model for GET /api/v1/audit/{request_id}.
    Mirrors the database row with JSON fields decoded back to dicts.
    """

    id: int
    request_id: str
    filename: Optional[str] = None
    clinical_notes: Optional[str] = None
    yolo_result: Optional[dict[str, Any]] = None
    densenet_result: Optional[dict[str, Any]] = None
    multimodal_result: Optional[dict[str, Any]] = None
    gemini_report: Optional[dict[str, Any]] = None
    created_at: Optional[str] = None

    model_config = {"from_attributes": True}
